    private void abrirOuCriarPedido() {
        try {
            // Simplificação: Assume-se que o primeiro pedido encontrado com status 'aberto' é o que deve ser usado.
            String checkSql = "SELECT id_pedido FROM Pedido WHERE status = 'aberto' LIMIT 1";
            con_cliente.executaSQL(checkSql);
            
            if (con_cliente.resultset.next()) {
                // Pedido em aberto encontrado
                currentPedidoId = con_cliente.resultset.getInt("id_pedido");
                // JOptionPane.showMessageDialog(this, "Pedido ID " + currentPedidoId + " reaberto.");
            } else {
                // Nenhum pedido em aberto, cria um novo
                // Simulação: id_cliente=1, id_funcionario=1, valor_total=0.00, status='aberto'
                String date = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date());
                String insertSql = "INSERT INTO Pedido (data_pedido, valor_total, id_cliente, id_funcionario, status) VALUES ('" + date + "', 0.00, 1, 1, 'aberto')";
                
                // Usa PreparedStatement para obter o ID gerado automaticamente
                try (PreparedStatement ps = con_cliente.conexao.prepareStatement(insertSql, Statement.RETURN_GENERATED_KEYS)) {
                    ps.executeUpdate();
                    ResultSet rs = ps.getGeneratedKeys();
                    if (rs.next()) {
                        currentPedidoId = rs.getInt(1);
                        // JOptionPane.showMessageDialog(this, "Novo Pedido ID " + currentPedidoId + " criado.");
                    }
                }
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao abrir ou criar pedido: " + e.getMessage(), "Erro de Banco", JOptionPane.ERROR_MESSAGE);
            currentPedidoId = -1; // Garante que o ID é inválido em caso de erro
        }
    }
    
    /**
     * Adiciona ou atualiza a quantidade de um item no pedido.
     * @param idProduto O ID do produto a ser adicionado.
     */
    private void adicionarItemAoPedido(int idProduto) {
        if (currentPedidoId == -1) {
            JOptionPane.showMessageDialog(this, "Nenhum pedido ativo. Impossível adicionar item.", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            // 1. Buscar preço e nome do produto
            String productSql = "SELECT nome, preco FROM Produto WHERE id_produto = " + idProduto;
            con_cliente.executaSQL(productSql);
            if (!con_cliente.resultset.next()) {
                JOptionPane.showMessageDialog(this, "Produto com ID " + idProduto + " não encontrado.", "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }
            String nomeProduto = con_cliente.resultset.getString("nome");
            double precoUnitario = con_cliente.resultset.getDouble("preco");
            
            // 2. Tentar encontrar o item_pedido
            String checkItemSql = "SELECT id_item_pedido, quantidade FROM Item_Pedido WHERE id_pedido = " + currentPedidoId + " AND id_produto = " + idProduto;
            con_cliente.executaSQL(checkItemSql);

            String updateOrInsertSql = "";
            if (con_cliente.resultset.next()) {
                // Item_Pedido já existe, apenas incrementa a quantidade
                int oldQty = con_cliente.resultset.getInt("quantidade");
                int newQty = oldQty + 1;
                double newSubtotal = newQty * precoUnitario;
                
                updateOrInsertSql = "UPDATE Item_Pedido SET quantidade = " + newQty + ", subtotal = " + newSubtotal + " WHERE id_pedido = " + currentPedidoId + " AND id_produto = " + idProduto;
                
            } else {
                // Item_Pedido não existe, insere um novo com quantidade = 1
                double subtotal = precoUnitario;
                updateOrInsertSql = "INSERT INTO Item_Pedido (id_pedido, id_produto, quantidade, preco_unitario, subtotal) VALUES (" + currentPedidoId + ", " + idProduto + ", 1, " + precoUnitario + ", " + subtotal + ")";
            }

            // 3. Executar a atualização/inserção
            Statement stmt = con_cliente.conexao.createStatement();
            stmt.executeUpdate(updateOrInsertSql);
            stmt.close();
            
            // 4. Atualizar a JTable e o contador visual
            atualizarTabelaPedidos();
            atualizarContadorVisual(idProduto, nomeProduto);
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao adicionar item ao pedido: " + e.getMessage(), "Erro de Banco", JOptionPane.ERROR_MESSAGE);
        }
    }

