    /**
     * Preenche a JTable (jTable1) com os ITENS do Pedido atual.
     */
    private void atualizarTabelaPedidos() {
        if (currentPedidoId == -1) return;

        // Query que junta Produto e Item_Pedido
        String sql = "SELECT P.nome, IP.quantidade, IP.preco_unitario, IP.subtotal, IP.id_item_pedido " +
                     "FROM Item_Pedido IP JOIN Produto P ON IP.id_produto = P.id_produto " +
                     "WHERE IP.id_pedido = " + currentPedidoId;
        
        try {
            con_cliente.executaSQL(sql);
        } catch (Exception e) {
            // Tenta criar um statement novo caso o anterior tenha sido fechado
            try {
                con_cliente.statement = con_cliente.conexao.createStatement(ResultSet.TYPE_SCROLL_SENSITIVE, ResultSet.CONCUR_READ_ONLY);
                con_cliente.executaSQL(sql);
            } catch (SQLException e2) {
                 JOptionPane.showMessageDialog(this, "Erro ao consultar itens do pedido: " + e2.getMessage(), "Erro de SQL", JOptionPane.ERROR_MESSAGE);
                 return;
            }
        }

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setNumRows(0); // Limpa as linhas

        // ⚠️ ATENÇÃO: Se o modelo da sua jTable1 não tiver 4 colunas, você terá erro de índice.
        try {
            // 1. Nome do Produto (ou Combo)
            // 2. Quantidade
            // 3. Preço Unitário
            // 4. Subtotal
            // (5. ID do Item_Pedido - Oculto, mas essencial para deletar)
            
            // Certifique-se que o modelo da sua JTable no design tem as colunas corretas.
            String[] colunas = new String[]{"Item", "Qtd", "Preço Unit.", "Subtotal", "ID_IP"};
            modelo.setColumnIdentifiers(colunas);
            
            while (con_cliente.resultset.next()) {
                modelo.addRow(new Object[]{
                    con_cliente.resultset.getString("nome"),
                    con_cliente.resultset.getInt("quantidade"),
                    String.format("R$ %.2f", con_cliente.resultset.getDouble("preco_unitario")),
                    String.format("R$ %.2f", con_cliente.resultset.getDouble("subtotal")),
                    con_cliente.resultset.getInt("id_item_pedido") // ID para exclusão
                });
            }
            
            // Oculta a coluna ID_IP (que é crucial para deletar)
            if (jTable1.getColumnCount() > 4) {
                jTable1.getColumnModel().getColumn(4).setMaxWidth(0);
                jTable1.getColumnModel().getColumn(4).setMinWidth(0);
                jTable1.getColumnModel().getColumn(4).setPreferredWidth(0);
            }

        } catch (SQLException erro) {
            JOptionPane.showMessageDialog(null, "\n Erro ao listar dados da tabela de Pedidos!! :\n " + erro, "Mensagem do Programa", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    
    
